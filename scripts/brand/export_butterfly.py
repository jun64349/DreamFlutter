r"""From the master docs/design/assets/butterfly.svg, write what the app uses:

  * app/lib/butterfly_art.dart         the paths and gradients, for ButterflyMark / ButterflyGlyph (theme.dart)
  * app/windows/runner/resources/app_icon.ico   the exe icon (16-256 px, each size rendered on its own)
  * app/assets/tray_icon.ico           the tray icon (16-48 px)

Icon files keep the original's colours (Windows has one icon per exe, so it cannot follow the theme).
Below 43 px the lines are widened to 1 px so they do not fade into grey hairs; larger sizes are the trace as is.
Run after trace_butterfly.py, with the same venv (see that file):

    & $env:TEMP\bf-trace\Scripts\python.exe scripts\brand\export_butterfly.py
"""
import io
import re
from pathlib import Path

import resvg_py
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SVG = ROOT / "docs" / "design" / "assets" / "butterfly.svg"
DART = ROOT / "app" / "lib" / "butterfly_art.dart"
APP_ICO = ROOT / "app" / "windows" / "runner" / "resources" / "app_icon.ico"
TRAY_ICO = ROOT / "app" / "assets" / "tray_icon.ico"

OPS = {"M": 0, "L": 1, "C": 2, "Z": 3}


def path_data(d):
    """SVG path text (M/L/C/Z, absolute) -> flat list: op code then its numbers."""
    out = []
    for op, num in re.findall(r"([MLCZ])|(-?\d+(?:\.\d+)?)", d):
        out.append(float(OPS[op]) if op else float(num))
    return out


def dart_list(nums):
    def f(v):
        s = ("%.2f" % v).rstrip("0").rstrip(".")
        return s if s not in ("-0", "") else "0"
    items = [f(v) for v in nums]
    lines = []
    for i in range(0, len(items), 20):
        lines.append("  " + ", ".join(items[i:i + 20]) + ",")
    return "<double>[\n" + "\n".join(lines) + "\n]"


def bounds(nums):
    xs, ys, i = [], [], 0
    while i < len(nums):
        n = {0: 2, 1: 2, 2: 6, 3: 0}[int(nums[i])]
        pts = nums[i + 1:i + 1 + n]
        xs += pts[0::2]
        ys += pts[1::2]
        i += 1 + n
    return min(xs), min(ys), max(xs), max(ys)


def export_dart(svg):
    grads = {}
    for gid, x1, y1, x2, y2, body in re.findall(
            r'<linearGradient id="([^"]+)" gradientUnits="userSpaceOnUse" x1="([\d.]+)" y1="([\d.]+)" '
            r'x2="([\d.]+)" y2="([\d.]+)">(.*?)</linearGradient>', svg):
        stops = [(float(o), int(t) / 100) for o, t in re.findall(r'offset="([\d.]+)"[^>]*--t:(\d+)%', body)]
        grads[gid] = (float(x1), float(y1), float(x2), float(y2), stops)

    pieces = {"band": [], "core": []}
    for pid, paint, d in re.findall(r'<path id="((?:band|core)-[^"]+)" ((?:class="\w+" )?fill="[^"]+") d="([^"]+)"/>', svg):
        kind = pid.split("-")[0]
        m = re.search(r"url\(#([^)]+)\)", paint)
        if m:
            x1, y1, x2, y2, stops = grads[m.group(1)]
            grad = "gradient: ButterflyGradient(Offset(%g, %g), Offset(%g, %g), [%s])" % (
                x1, y1, x2, y2, ", ".join("(%g, %g)" % s for s in stops))
        else:
            grad = None
        pieces[kind].append((pid, path_data(d), grad))

    def one(pid):
        return path_data(re.search(r'<path id="%s" d="([^"]+)"/>' % pid, svg).group(1))

    antennae = one("antenna-left") + one("antenna-right")
    outline = one("outline-left") + one("outline-right")
    x0, y0, x1, y1 = bounds(antennae + outline)

    out = ["// GENERATED by scripts/brand/export_butterfly.py from docs/design/assets/butterfly.svg. Do not edit by hand.",
           "// The user's butterfly, traced 1:1 (docs/design/brand.md, section 二.1). Coordinates are the SVG's 1024 grid.",
           "",
           "import 'dart:ui';",
           "",
           "/// The butterfly's extent (outline and antennae) in the 1024 grid.",
           "const butterflyBox = Rect.fromLTRB(%g, %g, %g, %g);" % (x0, y0, x1, y1),
           "",
           "/// A wing piece's gradient: from, to, and stops as (offset, t) where t mixes wing (0) into glow (1).",
           "class ButterflyGradient {",
           "  const ButterflyGradient(this.from, this.to, this.stops);",
           "  final Offset from;",
           "  final Offset to;",
           "  final List<(double, double)> stops;",
           "}",
           "",
           "/// One coloured area. [data] is a path: op codes (0 move, 1 line, 2 cubic, 3 close) each followed by its points.",
           "class ButterflyPiece {",
           "  const ButterflyPiece(this.id, this.data, {this.gradient});",
           "  final String id;",
           "  final List<double> data;",
           "",
           "  /// Null: a flat colour (wing for bands, core for cores).",
           "  final ButterflyGradient? gradient;",
           "}",
           "",
           "/// Builds a [Path] from [ButterflyPiece.data]-style numbers.",
           "Path butterflyPath(List<double> d) {",
           "  final p = Path()..fillType = PathFillType.evenOdd;",
           "  var i = 0;",
           "  while (i < d.length) {",
           "    switch (d[i].toInt()) {",
           "      case 0:",
           "        p.moveTo(d[i + 1], d[i + 2]);",
           "        i += 3;",
           "      case 1:",
           "        p.lineTo(d[i + 1], d[i + 2]);",
           "        i += 3;",
           "      case 2:",
           "        p.cubicTo(d[i + 1], d[i + 2], d[i + 3], d[i + 4], d[i + 5], d[i + 6]);",
           "        i += 7;",
           "      default:",
           "        p.close();",
           "        i += 1;",
           "    }",
           "  }",
           "  return p;",
           "}",
           ""]
    for kind, name, doc in (("band", "butterflyBands", "The coloured bands of the wings, under the cores; together they fill the wings up to the middle of the lines."),
                            ("core", "butterflyCores", "The light cores of the wings.")):
        out.append("/// %s" % doc)
        out.append("const %s = <ButterflyPiece>[" % name)
        for pid, data, grad in pieces[kind]:
            out.append("  ButterflyPiece('%s', %s%s)," % (pid, dart_list(data).replace("\n", "\n  "), ", " + grad if grad else ""))
        out.append("];")
        out.append("")
    out.append("/// Both antennae (filled shapes).")
    out.append("const butterflyAntennae = %s;" % dart_list(antennae))
    out.append("")
    out.append("/// Both wing outlines (filled shapes, even-odd).")
    out.append("const butterflyOutline = %s;" % dart_list(outline))
    out.append("")
    DART.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("%s: %d bytes" % (DART.relative_to(ROOT), DART.stat().st_size))


LINE = 24.0      # width of the original's lines in the 1024 grid
MIN_LINE = 1.0   # px: smaller icons widen the lines to this (optical thickening, like ButterflyPainter.minLine)


def render(svg, n):
    extra = MIN_LINE * 1024 / n - LINE
    if extra > 0:
        # stroke the filled line shapes in their own colour, which widens them on both sides
        svg = re.sub(r'(<g id="(?:antennae|outline)" class="line" fill="([^"]+)")',
                     r'\1 stroke="\2" stroke-width="%.1f" stroke-linejoin="round"' % extra, svg)
    png = bytes(resvg_py.svg_to_bytes(svg_string=svg, width=n, height=n))
    return Image.open(io.BytesIO(png)).convert("RGBA")


def export_ico(svg, path, sizes):
    images = [render(svg, s) for s in sizes]
    big = images[-1]
    big.save(path, format="ICO", sizes=[(s, s) for s in sizes], append_images=images[:-1])
    back = Image.open(path)
    print("%s: %s" % (path.relative_to(ROOT), sorted(back.info["sizes"])))


def main():
    svg = SVG.read_text(encoding="utf-8")
    export_dart(svg)
    export_ico(svg, APP_ICO, [16, 20, 24, 32, 40, 48, 64, 128, 256])
    export_ico(svg, TRAY_ICO, [16, 20, 24, 32, 40, 48])


if __name__ == "__main__":
    main()
