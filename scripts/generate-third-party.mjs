import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync, lstatSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { execFileSync } from 'node:child_process';
import { toolchainEnv } from '../core/src/agent/toolchain.ts';
const [target, repository, flutterRoot] = process.argv.slice(2);
if (!target || !repository || !flutterRoot) throw Error('usage: generate-third-party.mjs <package> <repo> <flutter-sdk>');
const folder = join(target, 'licenses'), texts = join(folder, 'texts'); mkdirSync(texts, { recursive: true });
const entries = [], visited = new Set();
function add(name, version, license, text, notice = '') {
  const id = String(entries.length), path = text ? `licenses/texts/${id}.txt` : null;
  if (text) writeFileSync(join(target, path), text);
  entries.push({ id, name, version, license: typeof license === 'string' ? license : '见随包许可证', path, notice });
}
function licenseText(path) {
  if (!existsSync(path)) return '';
  const files = readdirSync(path).filter(name => /^(?:licen[cs]e|copying|notice|unlicense)(?:[._-].*)?$/i.test(name));
  return files.flatMap(name => { const file = join(path, name); return lstatSync(file).isFile() && lstatSync(file).size < 16 * 1024 * 1024 ? [`${name}\n${readFileSync(file, 'utf8')}`] : []; }).join('\n\n');
}
function packageAt(path) {
  if (visited.has(path) || !existsSync(join(path, 'package.json'))) return; visited.add(path);
  const meta = JSON.parse(readFileSync(join(path, 'package.json'), 'utf8'));
  const text = licenseText(path); add(meta.name ?? basename(path), meta.version ?? '', meta.license, text, text ? '' : '此依赖未包含单独的许可证文本；请查看随包依赖的上游声明。');
  modules(join(path, 'node_modules'));
}
function modules(path) {
  if (!existsSync(path)) return;
  for (const item of readdirSync(path, { withFileTypes: true })) {
    if (!item.isDirectory() || item.isSymbolicLink() || item.name.startsWith('.')) continue;
    const child = join(path, item.name);
    if (item.name.startsWith('@')) { for (const pkg of readdirSync(child, { withFileTypes: true })) if (pkg.isDirectory() && !pkg.isSymbolicLink()) packageAt(join(child, pkg.name)); }
    else packageAt(child);
  }
}
const own = licenseText(repository); add('DreamFlutter', JSON.parse(readFileSync(join(target, 'build-info.json'), 'utf8')).version, own ? '见项目许可证' : '仓库未提供项目许可证', own, own ? '' : '此构建未随包提供项目许可证文件。');
add('Flutter SDK', '', '见 Flutter LICENSE', readFileSync(join(flutterRoot, 'LICENSE'), 'utf8'));
const dartLicense = join(flutterRoot, 'bin', 'cache', 'dart-sdk', 'LICENSE'); if (existsSync(dartLicense)) add('Dart SDK', '', '见 Dart LICENSE', readFileSync(dartLicense, 'utf8'));
const pluginManifest = join(repository, 'app', '.flutter-plugins-dependencies');
if (existsSync(pluginManifest)) {
  const plugins = JSON.parse(readFileSync(pluginManifest, 'utf8')).plugins ?? {};
  for (const plugin of Object.values(plugins).flat()) if (!visited.has(plugin.path)) { visited.add(plugin.path); const spec = existsSync(join(plugin.path, 'pubspec.yaml')) ? readFileSync(join(plugin.path, 'pubspec.yaml'), 'utf8') : ''; add(plugin.name, /^version:\s*(.*)$/m.exec(spec)?.[1] ?? '', '见插件许可证', licenseText(plugin.path)); }
}
// Dart's package configuration is generated by pub; include non-plugin packages too.
const packageConfig = join(repository, 'app', '.dart_tool', 'package_config.json');
if (existsSync(packageConfig)) {
  const base = new URL('file:///' + packageConfig.replaceAll('\\', '/'));
  for (const pkg of JSON.parse(readFileSync(packageConfig, 'utf8')).packages ?? []) {
    if (['dreamflutter', 'flutter', 'flutter_test', 'integration_test', 'flutter_web_plugins'].includes(pkg.name)) continue;
    const url = new URL(pkg.rootUri, base); const path = decodeURIComponent(url.pathname).replace(/^\/([A-Za-z]:)/, '$1');
    if (visited.has(path) || !existsSync(path)) continue; visited.add(path);
    const spec = existsSync(join(path, 'pubspec.yaml')) ? readFileSync(join(path, 'pubspec.yaml'), 'utf8') : '';
    add(pkg.name, /^version:\s*(.*)$/m.exec(spec)?.[1] ?? '', '见 Dart 依赖许可证', licenseText(path));
  }
}
modules(join(target, 'core', 'node_modules'));
const nodeLicense = join(folder, 'Node-LICENSE.txt'); add('Node.js', execFileSync(join(target, 'runtime', 'node.exe'), ['--version'], { encoding: 'utf8', windowsHide: true }).trim(), '见 Node.js LICENSE', existsSync(nodeLicense) ? readFileSync(nodeLicense, 'utf8') : licenseText(dirname(process.execPath)));
const pythonRoot = join(target, 'core', 'python'); if (existsSync(pythonRoot)) for (const dir of readdirSync(pythonRoot, { withFileTypes: true })) if (dir.isDirectory() && dir.name.startsWith('cpython-')) add('Python', dir.name, '见 Python 随包许可证', licenseText(join(pythonRoot, dir.name)));
const env = toolchainEnv();
const raw = (repo, tag, name) => execFileSync('curl.exe', ['-fL', '--silent', '--show-error', '--max-time', '20', `https://raw.githubusercontent.com/${repo}/${tag}/${name}`], { env, windowsHide: true, encoding: 'utf8', maxBuffer: 2 * 1024 * 1024 });
for (const [tool, repo, prefix, names] of [
  ['rg', 'BurntSushi/ripgrep', '', ['LICENSE-MIT', 'UNLICENSE']], ['fd', 'sharkdp/fd', 'v', ['LICENSE-MIT', 'LICENSE-APACHE']], ['uv', 'astral-sh/uv', '', ['LICENSE-MIT', 'LICENSE-APACHE']],
]) {
  const binary = join(target, 'core', 'bin', tool + '.exe'); if (!existsSync(binary)) continue;
  const version = /\d+\.\d+\.\d+/.exec(execFileSync(binary, ['--version'], { windowsHide: true, encoding: 'utf8' }))?.[0];
  if (!version) throw Error(`Could not read ${tool} version for its license`);
  add(tool, version, '见对应版本上游许可文本', names.map(name => `${name}\n${raw(repo, prefix + version, name)}`).join('\n\n'));
}
if (existsSync(join(target, 'app', 'velopack_libc.dll'))) add('Velopack', '1.2.161', '见对应版本上游许可证', raw('velopack/velopack', '1.2.161', 'LICENSE'));
for (const name of ['Debian-packages.txt', 'THIRD-PARTY.txt']) if (existsSync(join(folder, name))) add(name, '', '随包声明', readFileSync(join(folder, name), 'utf8'));
writeFileSync(join(folder, 'third-party.json'), JSON.stringify({ generatedAt: new Date().toISOString(), entries }, null, 2));
console.log(`Generated third-party manifest: ${entries.length} entries from actual package/SDK/license files`);
